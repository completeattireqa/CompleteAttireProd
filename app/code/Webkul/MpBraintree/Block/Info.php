namespace Webkul\MpBraintree\Block;

use Magento\Framework\Phrase;
use Magento\Payment\Block\ConfigurableInfo;

/**
 * Class Info
 */
class Info extends ConfigurableInfo
{
    /**
     * Returns label
     *
     * @param string $label
     * @return Phrase
     */
    protected function getLabel($label)
    {
        return __($label);
    }
}
